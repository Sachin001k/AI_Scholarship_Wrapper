/**
 * Generates supabase/seed.sql from the prototype seed catalog.
 *   npm run seed:sql
 * Runs with Node's built-in TypeScript type-stripping (Node ≥ 23.6).
 */
import { writeFileSync } from "node:fs";
import { OPPORTUNITIES, PROGRAMS, UNIVERSITIES } from "../src/lib/catalog/seed-data.ts";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a: string[]) => `${q(`{${a.map((x) => `"${x}"`).join(",")}}`)}::text[]`;
const json = (v: unknown) => (v === undefined || v === null ? "null" : `${q(JSON.stringify(v))}::jsonb`);

const out: string[] = ["-- Generated by scripts/generate-seed-sql.ts — do not edit by hand.", "begin;", ""];

const providers = new Map(OPPORTUNITIES.map((o) => [o.provider.id, o.provider]));
for (const p of providers.values()) {
  out.push(`insert into providers (code, name, type, country, website) values (${[p.id, p.name, p.type, p.country, p.website].map(q).join(", ")}) on conflict (code) do nothing;`);
}
out.push("");

for (const u of UNIVERSITIES) {
  out.push(
    `insert into universities (slug, name, country, city, website, financial_aid_url, blurb, accent) values (${[u.slug, u.name, u.country, u.city, u.website, u.financialAidUrl, u.blurb, u.accent].map(q).join(", ")}) on conflict (slug) do nothing;`,
  );
}
out.push("");

const uniSlug = new Map(UNIVERSITIES.map((u) => [u.id, u.slug]));
for (const p of PROGRAMS) {
  const uni = `(select id from universities where slug = ${q(uniSlug.get(p.universityId))})`;
  const prog = `(select id from programs where slug = ${q(p.slug)} and university_id = ${uni})`;
  out.push(
    `insert into programs (university_id, slug, name, level, field, duration_months, languages, entry_rules) values (${uni}, ${q(p.slug)}, ${q(p.name)}, ${q(p.level)}, ${q(p.field)}, ${p.durationMonths}, ${arr(p.languages)}, ${json(p.entryRequirements)}) on conflict (university_id, slug) do nothing;`,
  );
  for (const i of p.intakes) {
    const [local, zone] = i.deadline.kind === "FIXED" ? [i.deadline.local, i.deadline.zone] : [null, null];
    out.push(`insert into intakes (program_id, term, starts_on, deadline_local, deadline_zone) values (${prog}, ${q(i.term)}, ${q(i.startsOn)}, ${q(local)}, ${q(zone)});`);
  }
  for (const c of p.costs) {
    out.push(`insert into program_costs (program_id, audience, academic_year, tuition, fees, living) values (${prog}, ${q(c.audience)}, ${q(c.academicYear)}, ${json(c.tuition)}, ${json(c.fees)}, ${json(c.living)});`);
  }
}
out.push("");

const progKey = new Map(PROGRAMS.map((p) => [p.id, { slug: p.slug, uni: uniSlug.get(p.universityId)! }]));
for (const o of OPPORTUNITIES) {
  const [local, zone] = o.deadline.kind === "FIXED" ? [o.deadline.local, o.deadline.zone] : [null, null];
  const closesAt = local ? `(${q(local)}::timestamp at time zone ${q(zone)})` : "null";
  const opp = `(select id from opportunities where slug = ${q(o.slug)})`;
  out.push(
    `insert into opportunities (slug, kind, provider_id, basis, status, current_version, closes_local, closes_zone, closes_at, host_countries, nationalities_in, levels, fields, last_verified_at, is_sample) values (${q(o.slug)}, ${q(o.kind)}, (select id from providers where code = ${q(o.provider.id)}), ${q(o.basis ?? null)}, 'PUBLISHED', 1, ${q(local)}, ${q(zone)}, ${closesAt}, ${arr(o.hostCountries)}, ${arr(o.nationalitiesIn)}, ${arr(o.levels)}, ${arr(o.fields)}, ${q(o.lastVerifiedAt)}, ${o.sample ?? false}) on conflict (slug) do nothing;`,
  );
  const content = { title: o.title, summary: o.summary, description: o.description, documents: o.documents, steps: o.steps, officialUrl: o.officialUrl };
  out.push(
    `insert into opportunity_versions (opportunity_id, version, content, rules, award, loan_terms, published_at) values (${opp}, 1, ${json(content)}, ${json(o.rules)}, ${json(o.award)}, ${json(o.loanTerms)}, now()) on conflict do nothing;`,
  );
  for (const uid of o.universityIds ?? []) {
    out.push(`insert into opportunity_links (opportunity_id, university_id) values (${opp}, (select id from universities where slug = ${q(uniSlug.get(uid))}));`);
  }
  for (const pid of o.programIds ?? []) {
    const k = progKey.get(pid)!;
    out.push(
      `insert into opportunity_links (opportunity_id, program_id) values (${opp}, (select p.id from programs p join universities u on u.id = p.university_id where p.slug = ${q(k.slug)} and u.slug = ${q(k.uni)}));`,
    );
  }
}

out.push("", "commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`seed.sql: ${providers.size} providers, ${UNIVERSITIES.length} universities, ${PROGRAMS.length} programs, ${OPPORTUNITIES.length} opportunities`);
